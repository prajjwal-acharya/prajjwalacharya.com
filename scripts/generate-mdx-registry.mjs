import { mkdir, writeFile, readFile } from "node:fs/promises";
import { join } from "node:path";

/**
 * Builds `.generated/mdx/<collection>-registry.ts` for every collection
 * below, each a static `slug -> statically-imported MDX component` map.
 * Route pages read through these instead of compiling `body` (Velite's
 * `s.mdx()` output) at runtime via `new Function` — Cloudflare Workers
 * disallows runtime code generation, so every MDX document has to become
 * a real, build-time-resolved import instead.
 *
 * `slug` and `path` (the file's extension-less path relative to
 * `content/`, from `s.path()` in `velite.config.ts`) both come straight
 * from Velite's own build output (`.velite/<collection>.json`) — Velite
 * is the single source of truth for that mapping, so this script never
 * re-parses frontmatter itself. It only has to run *after* `velite build`
 * (see `next.config.ts`'s `ContentWebpackPlugin`, which always calls them
 * in that order).
 *
 * Plain `.mjs`, not `.ts`: this module is dynamically imported from
 * `next.config.ts` (transpiled by Next at config-load time, but its
 * runtime `import()` calls are not), so it has to be directly runnable by
 * Node with no separate TS loader in that context.
 */
const COLLECTIONS = [
  { name: "systems", veliteFile: ".velite/systems.json" },
  { name: "blueprints", veliteFile: ".velite/blueprints.json" },
];

const OUTPUT_DIR = ".generated/mdx";

/** `extract-it` -> `ExtractIt`, unique per collection so generated imports never collide. */
function importNameFor(slug) {
  const pascal = slug
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
  return /^[0-9]/.test(pascal) ? `_${pascal}` : pascal;
}

async function buildRegistry(name, veliteFile) {
  const items = JSON.parse(await readFile(veliteFile, "utf8"));

  // Sorted by slug (not file-system read order, which isn't guaranteed
  // stable across platforms) so the generated import list is
  // deterministic from run to run.
  const sorted = [...items].sort((a, b) => a.slug.localeCompare(b.slug));

  const entries = [];
  const seenImportNames = new Set();

  for (const item of sorted) {
    let importName = importNameFor(item.slug);
    while (seenImportNames.has(importName)) importName += "_";
    seenImportNames.add(importName);

    entries.push({ slug: item.slug, importName, path: item.path });
  }

  const imports = entries
    .map((entry) => `import ${entry.importName} from "@/content/${entry.path}.mdx";`)
    .join("\n");

  const registryEntries = entries
    .map((entry) => `  ${JSON.stringify(entry.slug)}: ${entry.importName},`)
    .join("\n");

  const accessorName = `get${name[0].toUpperCase()}${name.slice(1)}Component`;

  const contents = `/**
 * AUTO-GENERATED FILE.
 *
 * DO NOT EDIT MANUALLY.
 *
 * Generated by:
 * scripts/generate-mdx-registry.mjs
 */
import type { ComponentType } from "react";
import type { MDXComponentProps } from "@/.generated/mdx/mdx-component";
${imports ? `\n${imports}\n` : "\n"}
// \`as const\` keeps each key a literal type (e.g. \`keyof typeof ${name}Registry\`
// works for anything that already knows its slug at compile time).
export const ${name}Registry = {
${registryEntries}
} as const;

/**
 * Looks up a component by a slug that's only known at runtime (route
 * params, \`Velite\`-sourced metadata, etc.) — \`${name}Registry\` itself has
 * no index signature once typed via \`as const\`, so a plain \`string\` can't
 * index it directly without this cast.
 */
export function ${accessorName}(slug: string): ComponentType<MDXComponentProps> | undefined {
  return (${name}Registry as Record<string, ComponentType<MDXComponentProps> | undefined>)[slug];
}
`;

  await mkdir(OUTPUT_DIR, { recursive: true });
  await writeFile(join(OUTPUT_DIR, `${name}-registry.ts`), contents);
  console.log(`Generated ${OUTPUT_DIR}/${name}-registry.ts (${entries.length} entries)`);
}

export async function generateMdxRegistries() {
  await mkdir(OUTPUT_DIR, { recursive: true });
  await writeFile(
    join(OUTPUT_DIR, "mdx-component.ts"),
    `/**
 * AUTO-GENERATED FILE.
 *
 * DO NOT EDIT MANUALLY.
 *
 * Generated by:
 * scripts/generate-mdx-registry.mjs
 */
import type { MDXProps } from "mdx/types";

// \`@types/mdx\` already declares the ambient \`*.mdx\` module (default export
// typed as \`(props: MDXProps) => Element\`) — reusing its own prop type here
// instead of a hand-rolled one keeps every generated registry's component
// map assignable to it.
export type MDXComponentProps = MDXProps;
`,
  );

  for (const collection of COLLECTIONS) {
    await buildRegistry(collection.name, collection.veliteFile);
  }
}

// Run directly (`pnpm generate:mdx-registry`) as well as imported from
// `next.config.ts`, which calls `generateMdxRegistries()` itself on every
// `next dev`/`next build` — this guard just avoids doing the work twice
// when invoked as a standalone script.
if (import.meta.url === `file://${process.argv[1]}`) {
  generateMdxRegistries().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
